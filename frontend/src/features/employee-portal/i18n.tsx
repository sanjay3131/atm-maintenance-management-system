export type EmployeeLanguage = "ta" | "en";
export type TranslationValues = Record<string, string | number>;
export { employeeLanguageClasses } from "./employeeLanguage.utils";

export type EmployeeLanguageContextValue = {
  language: EmployeeLanguage;
  setLanguage: (language: EmployeeLanguage) => void;
  t: (key: EmployeeTranslationKey, values?: TranslationValues) => string;
};

export const STORAGE_KEY = "atm-employee-language";
export const EmployeeLanguageContext =
  createContext<EmployeeLanguageContextValue | null>(null);

export function readLanguagePreference(): EmployeeLanguage {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ta";
  } catch {
    return "ta";
  }
}

export function translate(
  language: EmployeeLanguage,
  key: EmployeeTranslationKey,
  values?: TranslationValues,
) {
  const template = language === "ta" ? employeeTamil[key] : employeeEnglish[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    values?.[name] === undefined ? match : String(values[name]),
  );
}

const englishContext: EmployeeLanguageContextValue = {
  language: "en",
  setLanguage: () => {},
  t: (key, values) => translate("en", key, values),
};

export function useEmployeeLanguage() {
  return useContext(EmployeeLanguageContext) ?? englishContext;
}

export function employeeJobStatusLabel(
  status: string,
  t: EmployeeLanguageContextValue["t"],
) {
  const labels: Record<string, EmployeeTranslationKey> = {
    PENDING: "Pending",
    ASSIGNED: "Assigned",
    ACCEPTED: "Accepted",
    IN_PROGRESS: "In progress",
    ON_HOLD: "On hold",
    COMPLETED: "Completed",
    VERIFIED: "Verified",
    APPROVED: "Approved",
    CLOSED: "Closed",
    REJECTED: "Rejected",
    CANCELLED: "Cancelled",
  };
  return labels[status] ? t(labels[status]) : status;
}

export function employeeDisplayLabel(
  label: string,
  t: EmployeeLanguageContextValue["t"],
) {
  return label in employeeEnglish
    ? t(label as EmployeeTranslationKey)
    : label;
}

export function employeeErrorMessage(
  message: string,
  fallback: EmployeeTranslationKey,
  language: EmployeeLanguage,
  t: EmployeeLanguageContextValue["t"],
) {
  if (language === "en") return message;
  const translated = employeeDisplayLabel(message, t);
  return translated === message ? t(fallback) : translated;
}
